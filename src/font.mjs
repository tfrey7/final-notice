export function hasGlyph(ch) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, ch);
}

// Width in logical pixels of `text` at `scale`, with `gap` pixels between letters.
export function textWidth(text, scale = 1, gap = 1) {
  if (text.length === 0) return 0;
  return (text.length * GLYPH_W + (text.length - 1) * gap) * scale;
}

// Every lit pixel of `text` as [x, y, row], where row is the glyph row (0-6) for shading.
export function textPixels(text, scale = 1, gap = 1) {
  const out = [];
  [...text].forEach((ch, i) => {
    const rows = GLYPHS[ch];
    if (!rows) throw new Error(`no glyph for ${JSON.stringify(ch)}`);
    const ox = i * (GLYPH_W + gap) * scale;
    rows.forEach((row, gy) => {
      for (let gx = 0; gx < GLYPH_W; gx++) {
        if (row[gx] !== '#') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) out.push([ox + gx * scale + sx, gy * scale + sy, gy]);
        }
      }
    });
  });
  return out;
}
