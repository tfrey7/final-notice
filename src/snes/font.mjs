const widthOf = (rows) => Math.max(...rows.map((r) => r.length));

// Every glyph as { w, rows }: FONT_H strings of exactly w characters.
export const GLYPHS = Object.fromEntries(Object.entries(DRAWN).map(([ch, drawn]) => {
  const w = widthOf(drawn);
  return [ch, { w, rows: Array.from({ length: FONT_H }, (_, r) => (drawn[r] || '').padEnd(w, '.')) }];
}));

