// Ellis Ward at Stage 1 size (24x40), Stage 2 size (16x32) and a 16x16 HUD portrait, drawn to
// docs/NES-ART-BIBLE.md: . transparent, 1 outline, hair, tie and shoes, 2 charcoal suit, 3 skin, shirt
// and highlights. Each frame is cut into 8x8 sprites here.
const art = {
  palettes: [[0x0f, 0x00, 0x37]],
  tiles: {},
  animations: {},
};

function add(name, fps, grids) {
  const frames = grids.map((grid) => {
    const parts = [];
    for (let ty = 0; ty < grid.length; ty += 8) {
      for (let tx = 0; tx < grid[0].length; tx += 8) {
        const rows = grid.slice(ty, ty + 8).map((r) => r.slice(tx, tx + 8).replaceAll('.', '0'));
        if (rows.every((r) => r === '00000000')) continue;
        const key = rows.join('');
        let tile = Object.keys(art.tiles).find((t) => art.tiles[t].join('') === key);
        if (!tile) {
          tile = `ward.${Object.keys(art.tiles).length}`;
          art.tiles[tile] = rows;
        }
        parts.push({ tile, x: tx, y: ty });
      }
    }
    return { palette: 0, parts };
  });
  art.animations[name] = { fps, frames };
}

