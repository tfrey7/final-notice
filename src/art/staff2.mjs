// Contract Counsel, the Facilities Supervisor (Stage 1) and the Records Custodian (Stage 2), drawn as
// pixel grids: . transparent, 1 outline, 2 clothes, 3 skin and light. Each frame is cut into 8x8 sprites
// here. The Supervisor is 4 sprites wide, so two of him on one row flicker with any company.
const art = {
  palettes: [
    [0x0f, 0x06, 0x30], // Counsel: black, red-tape oxblood suit, pale face
    [0x0f, 0x18, 0x37], // Supervisor: black, olive work jacket, tan skin and keys
    [0x0f, 0x14, 0x36], // Custodian: black, plum cardigan, pale pink skin
  ],
  tiles: {},
  animations: {},
};

function add(name, palette, fps, order, grids) {
  const frames = grids.map((grid) => {
    const parts = [];
    for (let ty = 0; ty < grid.length; ty += 8) {
      for (let tx = 0; tx < grid[0].length; tx += 8) {
        const rows = grid.slice(ty, ty + 8).map((r) => r.slice(tx, tx + 8).replaceAll('.', '0'));
        if (rows.every((r) => r === '00000000')) continue;
        const key = rows.join('');
        let tile = Object.keys(art.tiles).find((t) => art.tiles[t].join('') === key);
        if (!tile) {
          tile = `${name.split('.')[0]}.${Object.keys(art.tiles).length}`;
          art.tiles[tile] = rows;
        }
        parts.push({ tile, x: tx, y: ty });
      }
    }
    return { palette, parts };
  });
  art.animations[name] = { fps, frames: order.map((i) => frames[i]) };
}

