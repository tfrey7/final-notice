// Ellis Ward, Frank Mercer and the Security Associate at Stage 1 size (24x40, three sprites across),
// drawn to docs/NES-ART-BIBLE.md: . transparent, 1 outline, 2 clothes, 3 skin and shirt. Each frame
// is cut into 8x8 sprites here.
const art = {
  palettes: [
    [0x0f, 0x00, 0x37], // ward: black, charcoal suit, tan skin and shirt
    [0x0f, 0x12, 0x37], // mercer: black, blue suit, tan skin, sandy hair
    [0x0f, 0x17, 0x36], // associate: black, rust uniform, pink skin
  ],
  tiles: {},
  animations: {},
};

function add(name, palette, fps, order, grids) {
  const frames = grids.map((grid) => {
    const parts = [];
    for (let ty = 0; ty < grid.length; ty += 8) {
      for (let tx = 0; tx < grid[0].length; tx += 8) {
        const rows = grid.slice(ty, ty + 8).map((r) => r.slice(tx, tx + 8).replaceAll('.', '0'));
        if (rows.every((r) => r === '00000000')) continue;
        const key = rows.join('');
        let tile = Object.keys(art.tiles).find((t) => art.tiles[t].join('') === key);
        if (!tile) {
          tile = `${name.split('.')[0]}.${Object.keys(art.tiles).length}`;
          art.tiles[tile] = rows;
        }
        parts.push({ tile, x: tx, y: ty });
      }
    }
    return { palette, parts };
  });
  art.animations[name] = { fps, frames: order.map((i) => frames[i]) };
}

