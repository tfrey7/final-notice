function cell(rows) {
  const out = [];
  for (let r = 0; r < CELL; r++) out.push((rows[r] ?? '').padEnd(CELL, '.'));
  return out;
}

// Every glyph as 8 strings of 8 characters, '#' lit and '.' clear.
export const GLYPHS = Object.fromEntries(Object.entries(DRAWN).map(([ch, rows]) => [ch, cell(rows)]));

export function hasGlyph(ch) {
  return Object.hasOwn(GLYPHS, ch);
}

export function glyph(ch) {
  return GLYPHS[ch] ?? GLYPHS['?'];
}

export function missingGlyphs(text) {
  return [...new Set([...text].filter((ch) => !hasGlyph(ch)))];
}

// Width in pixels: fixed width, one cell a character.
export function measure(text) {
  return [...text].length * CELL;
}

// Word-wraps text into lines of at most `cols` characters, then groups them into pages of `rows`.
export function wrap(text, cols = BOX_COLS, rows = BOX_ROWS) {
  const lines = [];
  let line = '';
  for (let word of text.split(/\s+/).filter(Boolean)) {
    while (word.length > cols) {
      if (line) { lines.push(line); line = ''; }
      lines.push(word.slice(0, cols));
      word = word.slice(cols);
    }
    if (!line) line = word;
    else if (line.length + 1 + word.length <= cols) line += ` ${word}`;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  const pages = [];
  for (let i = 0; i < lines.length; i += rows) pages.push(lines.slice(i, i + rows));
  return pages;
}
